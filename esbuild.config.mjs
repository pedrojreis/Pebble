import esbuild from "esbuild";
import process from "process";
import { builtinModules } from "node:module";
import path from "node:path";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

/**
 * The editor window runs in its own BrowserWindow, so it can't share
 * Obsidian's CodeMirror. Bundle it separately for the browser and expose
 * the result to the plugin as the string module "pebble-editor-bundle".
 */
const editorBundlePlugin = {
	name: "pebble-editor-bundle",
	setup(build) {
		build.onResolve({ filter: /^pebble-editor-bundle$/ }, () => ({
			path: "pebble-editor-bundle",
			namespace: "pebble-editor",
		}));
		build.onLoad({ filter: /.*/, namespace: "pebble-editor" }, async () => {
			const result = await esbuild.build({
				entryPoints: ["src/editor/index.ts"],
				bundle: true,
				write: false,
				format: "iife",
				platform: "browser",
				target: "es2018",
				minify: true,
				legalComments: "none",
				metafile: true,
			});
			return {
				contents: result.outputFiles[0].text,
				loader: "text",
				watchFiles: Object.keys(result.metafile.inputs).map((file) =>
					path.resolve(file),
				),
			};
		});
	},
};

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ["src/main.ts"],
	bundle: true,
	plugins: [editorBundlePlugin],
	loader: { ".css": "text", ".html": "text" },
	external: [
		"obsidian",
		"electron",
		"@electron/remote",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtinModules,
	],
	format: "cjs",
	target: "es2018",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outfile: "main.js",
	minify: prod,
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
